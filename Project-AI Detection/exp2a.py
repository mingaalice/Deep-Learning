# Batch GPT2 Sequence Log Probability
def gpt2_logprob(text):

    if text is None or str(text).strip() == "":
        return -1e9   # extreme low scores，i.e. randomly pick human or ai

    inputs = gpt2_tokenizer(
        text,
        padding=True,
        truncation=True,
        max_length=1024,
        return_tensors="pt"
    ).to(device)

    input_ids = inputs["input_ids"]
    attention_mask = inputs["attention_mask"]

    with torch.no_grad():
        outputs = gpt2(
            input_ids=input_ids,
            attention_mask=attention_mask
            )
        logits = outputs.logits

    # shift
    shift_logits = logits[:, :-1]
    shift_labels = input_ids[:, 1:]
    shift_mask = attention_mask[:, 1:]

    # token log probabilities
    log_probs = F.log_softmax(
        shift_logits,
        dim=-1
    )

    token_log_probs = log_probs.gather(
        dim=-1,
        index=shift_labels.unsqueeze(-1)
    ).squeeze(-1)

    token_log_probs = token_log_probs * shift_mask
    seq_log_probs = token_log_probs.sum(dim=1)

    return seq_log_probs.cpu().numpy()

# DectGPT Score
def detectgpt_score(
        text,
        num_perturb=10):

    # original
    orig_logprob = gpt2_logprob(text)

    # perturbations
    perturbed = t5_perturb(
        text,
        num_perturb=num_perturb
    )

    # perturbation scores
    pert_scores = gpt2_logprob(
        perturbed
    )

    # DetectGPT score: (orig - μ)/σ
    mu = pert_scores.mean()
    sigma = pert_scores.std()

    if sigma < 1e-6:
        sigma = 1e-6
    score = (orig_logprob - mu) / sigma

    return score

