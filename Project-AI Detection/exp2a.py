# Span Masking
def mask_text(text,
              mask_ratio=0.15,
              mean_span_length=3):

    # T5 sentencepiece tokens
    text = t5_tokenizer.decode(
    t5_tokenizer(
        text,
        truncation=True,
        max_length=512
    )["input_ids"],
    skip_special_tokens=True
)
    tokens = t5_tokenizer.tokenize(text)

    n_tokens = len(tokens)

    if n_tokens == 0:
        return text

    target_mask = max(1, int(mask_ratio * n_tokens))

    masked_tokens = []

    num_masked = 0
    sentinel_id = 0

    i = 0

    while i < n_tokens:
        if num_masked >= target_mask:
            masked_tokens.extend(tokens[i:])
            break

        if random.random() < mask_ratio:

            span_len = max(
                1,
                int(random.expovariate(1 / mean_span_length))
            )

            span_len = min(
                span_len,
                target_mask - num_masked,
                n_tokens - i
            )

            masked_tokens.append(f"<extra_id_{sentinel_id}>")

            sentinel_id += 1

            i += span_len
            num_masked += span_len

        else:

            masked_tokens.append(tokens[i])
            i += 1

    masked_text = t5_tokenizer.convert_tokens_to_string(masked_tokens)

    return masked_text

# Recover spans using T5
def fill_masks(masked_text):

    inputs = t5_tokenizer(
        masked_text,
        return_tensors="pt",
        truncation=True,
        max_length=1024
    ).to(device)

    with torch.no_grad():

        outputs = t5.generate(
            **inputs,
            do_sample=True,
            top_p=0.95,
            temperature=1.0,
            max_new_tokens=96
        )

    generated = t5_tokenizer.decode(
        outputs[0],
        skip_special_tokens=False
    )

    return generated

# Replace <extra_id_i> with generated spans
def apply_fills(masked_text, generated_text):

    # split by sentinels
    fills = re.split(r"<extra_id_\d+>", generated_text)

    # remove first empty element
    fills = fills[1:]

    result = masked_text

    for i, fill in enumerate(fills):

        fill = fill.replace("</s>", "").strip()

        result = result.replace(
            f"<extra_id_{i}>",
            fill,
            1
        )

    # remove remaining sentinels if any
    result = re.sub(r"<extra_id_\d+>", "", result)

    result = re.sub(r"\s+", " ", result).strip()

    return result

# Generate batch T5 perturbations
def t5_perturb(text,
               num_perturb=10):

    masked_texts = [
        mask_text(text)
        for _ in range(num_perturb)
    ]

    inputs = t5_tokenizer(
        masked_texts,
        padding=True,
        truncation=True,
        max_length=1024,
        return_tensors="pt"
    ).to(device)

    with torch.no_grad():
        outputs = t5.generate(
            **inputs,
            do_sample=True,
            top_p=0.95,
            temperature=1.0,
            max_new_tokens=96
        )

    generated = t5_tokenizer.batch_decode(
        outputs,
        skip_special_tokens=False
    )

    perturbations = []
    for masked, gen in zip(masked_texts, generated):

        perturbations.append(
            apply_fills(masked, gen)
        )

    return perturbations

