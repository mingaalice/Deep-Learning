"""## 1b.5 Calculate a Score to Evaluate"""

# Weighted Greenlist Dictionary
gpt_dict = dict(
    zip(
        gpt_green_df.token,
        gpt_green_df.z
    )
)

llama_dict = dict(
    zip(
        llama_green_df.token,
        llama_green_df.z
    )
)

mistral_dict = dict(
    zip(
        mistral_green_df.token,
        mistral_green_df.z
    )
)

# Score
def weighted_score(text, green_dict):

    score = 0

    for token, z in green_dict.items():

        if token is None:
            continue

        token = str(token)

        if token == "nan" or token == "None":
            continue

        if not isinstance(z, (int, float)):
            continue

        score += text.count(token) * float(z)

    return score

# Multi-class Score
def predict_model(
    text
):

    s_gpt = weighted_score(
        text,
        gpt_dict
    )

    s_llama = weighted_score(
        text,
        llama_dict
    )

    s_mistral = weighted_score(
        text,
        mistral_dict
    )

    scores = [
        s_gpt,
        s_llama,
        s_mistral
    ]

    return (
        np.argmax(scores)
        + 1
    )

