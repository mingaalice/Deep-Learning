"""## 1b.2 Observed Counts and Expected Counts"""

# Observed Counts
def observed_counts(
    texts,
    tokenizer
):

    counter = Counter()

    for text in tqdm(texts):

        ids = tokenizer.encode(
            text,
            truncation=True,
            max_length=1024
        )

        counter.update(ids)

    return counter

# Expected Counts
def expected_counts(
    texts,
    model,
    tokenizer,
    device=device,
    batch_size=8,       # use batch to accelerate
    top_k=30,
    max_length=512
):

    expected = defaultdict(float)

    model.eval()

    for i in tqdm(range(0, len(texts), batch_size)):

        batch_texts = texts[i:i+batch_size]

        inputs = tokenizer(
            batch_texts,
            return_tensors="pt",
            padding=True,
            truncation=True,
            max_length=max_length
        )

        inputs = {k: v.to(device) for k, v in inputs.items()}

        with torch.no_grad():

            outputs = model(**inputs)
            logits = outputs.logits

            probs = torch.softmax(logits, dim=-1)

        # probs: [B, T, V]
        batch_size_actual = probs.shape[0]

        for b in range(batch_size_actual):

            seq_len = inputs["attention_mask"][b].sum().item()

            for t in range(seq_len - 1):

                top_p, top_idx = torch.topk(
                    probs[b, t],
                    k=top_k
                )

                top_p = top_p.cpu()
                top_idx = top_idx.cpu()

                for p, idx in zip(top_p, top_idx):

                    expected[int(idx)] += float(p)

    return expected

"""## 1b.3 Comparison Within Each 2 Models
$$
z_i^{j,k} = \frac{N_i^{j}-E_i^{k}}{\sqrt{E_i^{k}}},
$$
where $N_i^{j}$ denotes the actual frequency of token $i$ in text generated by $j$, and $E_i^k$ denotes the expected frequency of token $i$ genereated by $k$. From our assumption, this indicator can capture "greenlist" of different models.
"""

# Using z-scores
def recover_greenlist(
    texts,
    model,
    tokenizer,
    device=device,
    batch_size=8,
    top_k=30,
    max_length=512
):

    obs = observed_counts(
        texts,
        tokenizer
    )

    exp = expected_counts(
        texts,
        model,
        tokenizer
    )

    rows = []

    all_tokens = (
        set(obs.keys())
        |
        set(exp.keys())
    )

    for tid in all_tokens:

        N = obs.get(tid,0)

        E = exp.get(tid,0)

        if E < 30:
            continue

        z = (
            N-E
        ) / np.sqrt(E)

        token_str = (
            tokenizer.decode(
                [tid],
                clean_up_tokenization_spaces=True
            )
            .lower()
            .strip()
        )

        rows.append(
            [
                tid,
                token_str,
                N,
                E,
                z
            ]
        )

    df = pd.DataFrame(
        rows,
        columns=[
            "token_id",
            "token",
            "N",
            "E",
            "z"
        ]
    )

    df = df.sort_values(
        "z",
        ascending=False
    )

    return df.head(top_k)

